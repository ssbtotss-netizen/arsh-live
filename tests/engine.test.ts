import { newRoom, roomEvent, roomClockOp, roomTick, roomLive } from "../arsh-live/src/engine/room.js";
import { migrateRules, remaining, timerValue, giftSeconds, MIN, HOUR } from "../arsh-live/src/engine/clock.js";
import { entries } from "../arsh-live/src/engine/leaderboard.js";
import { newWidget } from "../arsh-live/src/engine/defs.js";
let fails=0; const ok=(c:any,m:string)=>{console.log((c?"PASS ":"FAIL ")+m); if(!c) fails++};
const u=(n:string)=>({id:n,name:n});
let now=1_000_000;
const R=newRoom(); const S=R.C.subathon; delete S.rules.list; migrateRules(S); // الإعدادات القديمة: نفس السلوك بعد الترقية
ok(remaining(S,now)===2*HOUR,"starts at 2h");
roomEvent(R,{type:"gift",user:u("a"),gift:"وردة",giftId:5655,value:1,count:1,id:"g1"},now);
ok(remaining(S,now)===2*HOUR,"gifts ignored before subathon starts");
roomClockOp(R,{target:"subathon",op:"start"},now);
now+=10_000; ok(remaining(S,now)===2*HOUR-10_000,"counts down with server time");
let r=roomEvent(R,{type:"gift",user:u("a"),gift:"Rose",giftId:5655,value:1,count:1,id:"g2"},now);
ok(remaining(S,now)===2*HOUR-10_000+5000,"rose (by id) adds 5s");
r=roomEvent(R,{type:"gift",user:u("a"),gift:"Rose",giftId:5655,value:1,count:1,id:"g2"},now);
ok(r.dup&&remaining(S,now)===2*HOUR-5000,"duplicate gift id ignored (no double count)");
ok(R.D.tot.gifts===2,"leaderboard also not double counted");
roomEvent(R,{type:"gift",user:u("b"),gift:"قلب",giftId:5487,value:25,count:5,id:"g3"},now);
ok(remaining(S,now)===2*HOUR-5000+50_000,"streak of 5 hearts adds 5×10s");
const before=remaining(S,now);
roomEvent(R,{type:"gift",user:u("c"),gift:"Unknown big",giftId:9999,value:700,count:1,diamonds:700,id:"g4"},now);
ok(remaining(S,now)-before===120_000,"unknown gift ≥500 diamonds uses 'medium' tier (2 min)");
const b2=remaining(S,now);
roomEvent(R,{type:"like",user:u("d"),count:600,id:"l1"},now); ok(remaining(S,now)===b2,"600 likes: not yet 1000");
roomEvent(R,{type:"like",user:u("d"),count:900,id:"l2"},now); ok(remaining(S,now)-b2===30_000&&S.likeAcc===500,"1500 likes → +30s, carry 500");
const b3=remaining(S,now); roomEvent(R,{type:"follow",user:u("e"),id:"f1"},now); ok(remaining(S,now)-b3===10_000,"follow +10s");
roomClockOp(R,{target:"subathon",op:"config",config:{rules:{follow:{enabled:false}}}},now);
const b4=remaining(S,now); roomEvent(R,{type:"follow",user:u("f"),id:"f2"},now); ok(remaining(S,now)===b4,"follow method disabled independently");
roomClockOp(R,{target:"subathon",op:"add",ms:-MIN,source:"manual"},now); ok(remaining(S,now)===b4-MIN,"manual -1 min");
roomClockOp(R,{target:"subathon",op:"pause"},now); now+=60_000; ok(remaining(S,now)===b4-MIN,"paused: time frozen");
roomClockOp(R,{target:"subathon",op:"resume"},now); now+=1000; ok(remaining(S,now)===b4-MIN-1000,"resumed");
roomLive(R,true,now); roomLive(R,false,now); ok(S.status==="paused"&&S.autoPaused,"auto pause on stream disconnect");
roomLive(R,true,now); ok(S.status==="running","auto resume on reconnect");
roomClockOp(R,{target:"subathon",op:"config",config:{maxMs:3*HOUR}},now);
roomClockOp(R,{target:"subathon",op:"add",ms:5*HOUR,source:"manual"},now); ok(remaining(S,now)===3*HOUR,"max remaining cap");
roomClockOp(R,{target:"subathon",op:"config",config:{rules:{goal:{enabled:true,metric:"likes",target:2000,sec:600}}}},now);
const b5=remaining(S,now)-MIN*20; roomClockOp(R,{target:"subathon",op:"add",ms:-MIN*20,source:"manual"},now);
roomEvent(R,{type:"like",user:u("d"),count:600,id:"l3"},now); ok(remaining(S,now)-b5===600_000+0||remaining(S,now)-b5===630_000,"goal reached adds 10 min once");
const b6=remaining(S,now); roomEvent(R,{type:"like",user:u("d"),count:10,id:"l4"},now); ok(remaining(S,now)===b6,"goal not re-added");
now+=3*HOUR+1000; let t=roomTick(R,now); ok(S.status==="ended"&&t.logs.length===1,"ends automatically by server tick");
roomEvent(R,{type:"gift",user:u("a"),giftId:7312,gift:"Universe",value:44999,count:1,id:"g9"},now); ok(remaining(S,now)===0,"no time added after end");
roomClockOp(R,{target:"subathon",op:"reset"},now); ok(S.status==="idle"&&remaining(S,now)===2*HOUR&&S.totalAddedMs===0,"reset");
// timers
const st=R.C.timers.find((x:any)=>x.id==="stream");
roomClockOp(R,{target:"timers",op:"create",kind:"countdown",config:{name:"وقت السحب",durationMs:5*MIN}},now);
const cd=R.C.timers[2]; roomClockOp(R,{target:cd.id,op:"start"},now); roomClockOp(R,{target:"stream",op:"reset"},now); roomClockOp(R,{target:"stream",op:"start"},now);
now+=60_000; ok(timerValue(cd,now)===4*MIN&&timerValue(st,now)===MIN,"two timers run independently");
roomClockOp(R,{target:cd.id,op:"pause"},now); now+=60_000; ok(timerValue(cd,now)===4*MIN&&timerValue(st,now)===2*MIN,"pausing one doesn't affect other");
roomClockOp(R,{target:cd.id,op:"resume"},now); now+=5*MIN; roomTick(R,now); ok(cd.status==="ended","countdown ends");
// leaderboard lists
ok(entries(newWidget("recentGifts",{topN:3}),R.D,R.H)[0].v===44999,"recent supporters newest first");
ok(entries(newWidget("recentFollows",{topN:5}),R.D,R.H).length===2,"recent followers");
ok(entries(newWidget("interact",{topN:20}),R.D,R.H).length>=4,"most interactive list");
ok(giftSeconds({gifts:{enabled:true,table:[],perDiamondSec:2}},{value:30,count:3,diamonds:10})===60,"per-diamond fallback");
console.log(fails?`${fails} FAILED`:"ALL PASS"); process.exit(fails?1:0);
